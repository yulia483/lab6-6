print('Введите числа через пробел: ')
a = [int(x) for x in input().split()]
# изначально считаем, что список отсортирован
s=True
#идем до предпоследнего элемента 
for x in range(len(a)-1):
    #проверяем поряд элементов 
    if a[x]>a[x+1]:
    #если нарушен, то s будет ложь
        s=False
        break
if s:
    print("список отстортирован")
else:
    print("список не  отстортирован")