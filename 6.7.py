# создаем пустую очередь
q = []
# enqueue — добавляем элементы в конец очереди
q.append(10)
print("добавили 10, очередь:", q)
q.append(20)
print("добавили 20, очередь:", q)
q.append(30)
print("добавили 30, очередь:", q)
# dequeue — забираем элементы из начала очереди (4-й раз проверит пустую очередь)
for i in range(4):
    # проверяем краевой случай, если очередь пуста
    if len(q) == 0:
        print("очередь пуста, забирать нечего")
    else:
        # удаляем и запоминаем первый элемент (индекс 0)
        v = q.pop(0)
        print("забрали:", v, "| осталось:", q)